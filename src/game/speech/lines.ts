// 話しかた(公式の「こすくまくんとおしゃべり」 osyaberi.kosukuma.com に合わせる):
//   「やあ。……なんか話してよ。うん、聞くよ。」
//   「自転してるのに、ぼくら誰も回ってる感じしないよね。……」
//  - **漢字は普通に使う**(ひらがな縛りにしない。ここを外すと別人になる)
//  - 一人称は「ぼく」「ぼくら」
//  - 「〜よね。」「〜よ。」「〜けど。」で、同意を求めたり言いさしたりする
//  - 「……」で間をつくる。言い切らないのがこの子らしさ
//  - **豆知識は事実の羅列にしない**。「へえ」ではなく「そうだよね」と思わせる
//    つぶやきにする。× 地球は時速1670kmで自転しています
//                    ○ 自転してるのに、ぼくら誰も回ってる感じしないよね
//  - 1行は最大20文字くらい(吹き出しが2行に収まる長さ)。
//    どうしてもここで折りたい、というときは本文に \n を書けば尊重される
//  - おなじ場面で何度も出るので、被らないように多めに用意する

